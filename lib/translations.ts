export type TranslationValues = Record<string, string | number>;
export function translate(
  text: string,
  locale: Locale,
  values?: TranslationValues,
) {
  const result = locale === "en" ? en[text] || text : text;
  return values
    ? result.replace(/\{(\w+)\}/g, (token, key) => String(values[key] ?? token))
    : result;
}
